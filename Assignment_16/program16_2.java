class Logic
{
    void checkEvenOdd(int iNum)
    {
        if(iNum % 2 == 0)
        {
            System.out.println(iNum + " is an Even number.");
        }
        else
        {
            System.out.println(iNum + " is an Odd number.");
        }
    }
}

//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry Point function for the application
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class program16_2
{
    public static void main(String args[])
    {
        Logic obj = new Logic();
        obj.checkEvenOdd(7);
    }
}

