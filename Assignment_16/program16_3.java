class Logic
{
    void findFactorial(int iNum)
    {
        int iFact = 1;

        for(int i = 1; i <= iNum; i++)
        {
            iFact = iFact * i;
        }

        System.out.println("Factorial of " + iNum + " is : " + iFact);
    }
}

//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry Point function for the application
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class program16_3
{
    public static void main(String args[])
    {
        Logic obj = new Logic();
        obj.findFactorial(5);
    }
}

