class Logic
{
    void countDigits(int iNum)
    {
        int iCnt = 0;
        int temp = iNum;

        if(iNum == 0)
        {
            iCnt = 1;
        }
        else
        {
            while(iNum != 0)
            {
                iNum = iNum / 10;
                iCnt++;
            }
        }

        System.out.println("Number of digits in " + temp + " is : " + iCnt);
    }
}

//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry Point function for the application
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class program16_5
{
    public static void main(String args[])
    {
        Logic obj = new Logic();
        obj.countDigits(7865);
    }
}

