//
//  Class Name : Logic
//  Function Name : calculatePower
//  Description :   It is used to calculate the power of a given base raised to an exponent.
//  Input :         Integer
//  Author :        Mukta Dhanraj Mane
//  Date :          31/10/2025
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class Logic
{
    void calculatePower(int iBase, int iExp)
    {
        int iCnt = 0;
        int iResult = 1;

        for(iCnt = 1; iCnt <= iExp; iCnt++)
        {
            iResult = iResult * iBase;
        }

        System.out.println(iBase + " raised to " + iExp + " is: " + iResult);
    }
}

//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry Point function for the application
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class program19_5
{
    public static void main(String args[])
    {
        Logic obj = new Logic();
        obj.calculatePower(2, 5);
    }
}

